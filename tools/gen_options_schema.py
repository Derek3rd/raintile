#!/usr/bin/env python3
"""Writes src/Options/SchemaData.cs from the schema in Scripts/Options.ps1.

    python tools/gen_options_schema.py [--check]

The pages, the menu and the default values of the Options window are written
once, in @Resources/Scripts/Options.ps1 ($schema, $navTree, $defaults, ...).
The native window (src/Options) uses the same data, generated from there:
PowerShell (pwsh, or powershell on Windows) loads the script with -NoGui and
prints it as JSON, this script turns it into C#. With --check it only tells
whether SchemaData.cs is up to date (exit code 1 if not).
"""

import json
import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'src', 'Options', 'SchemaData.cs')

DUMP = r'''
$ErrorActionPreference = 'Stop'
. (Join-Path $env:RT_ROOT '@Resources/Scripts/Options.ps1') -Resources (Join-Path $env:RT_ROOT '@Resources/.') -NoGui
$labels = [ordered]@{}; foreach ($k in ($STORE_LABELS.Keys | Sort-Object)) { $labels[$k] = $STORE_LABELS[$k] }
$keys = [ordered]@{}; foreach ($k in ($KEY_LABELS.Keys | Sort-Object)) { $keys[$k] = $KEY_LABELS[$k] }
$defs = [ordered]@{}; foreach ($k in ($defaults.Keys | Sort-Object)) { $defs[$k] = $defaults[$k] }
[ordered]@{ schema = $schema; nav = $navTree; defaults = $defs; pad = $GAMEPAD_BUTTONS; sources = $SOURCES; labels = $labels; keyLabels = $keys } |
    ConvertTo-Json -Depth 12
'''


def q(s):
    if s is None:
        return 'null'
    out = '"'
    for ch in str(s):
        if ch == '\\':
            out += '\\\\'
        elif ch == '"':
            out += '\\"'
        elif ord(ch) > 126 or ord(ch) < 32:
            out += '\\u%04X' % ord(ch)
        else:
            out += ch
    return out + '"'


def num(v):
    return repr(float(v)) if isinstance(v, (int, float)) else str(v)


def generate(d):
    lines = []
    w = lines.append
    w('// GENERATED by tools/gen_options_schema.py from the schema of')
    w('// @Resources/Scripts/Options.ps1 (pages, menu, defaults): do not edit by hand.')
    w('using System.Collections.Generic;')
    w('namespace RaintileOptions')
    w('{')
    w('    public static partial class Schema')
    w('    {')
    w('        public static readonly List<Page> Pages = new List<Page>')
    w('        {')
    for p in d['schema']:
        w('            new Page { Id = %s, Title = %s, Icon = 0x%X, Desc = %s, Groups = new List<Group>'
          % (q(p['Id']), q(p['Title']), p['Icon'], q(p.get('Desc'))))
        w('            {')
        for g in p.get('Groups') or []:
            flags = ''
            if g.get('Found'):
                flags += ', Found = true'
            if g.get('Other'):
                flags += ', Other = true'
            w('                new Group { Title = %s, Help = %s%s, Items = new List<Item>' % (q(g.get('Title')), q(g.get('Help')), flags))
            w('                {')
            for it in g.get('Items') or []:
                extra = []
                if 'Choices' in it:
                    extra.append('Choices = new List<string[]> { ' + ', '.join(
                        'new[] { %s, %s }' % (q(c[0]), q(c[1])) for c in it['Choices']) + ' }')
                if 'Pair' in it:
                    extra.append('Pair = new[] { ' + ', '.join(q(x) for x in it['Pair']) + ' }')
                for k in ('Min', 'Max', 'Step'):
                    if k in it:
                        extra.append('%s = %s' % (k, num(it[k])))
                if 'Unit' in it:
                    extra.append('Unit = %s' % q(it['Unit']))
                if 'Axis' in it:
                    extra.append('Axis = %s' % q(it['Axis']))
                w('                    new Item { Kind = %s, Key = %s, Label = %s, Help = %s%s },' % (
                    q(it['Kind']), q(it['Key']), q(it['Label']), q(it.get('Help') or ''),
                    (', ' + ', '.join(extra)) if extra else ''))
            w('                } },')
        w('            } },')
    w('        };')
    w('')
    w('        public static readonly List<NavNode> NavTree = new List<NavNode>')
    w('        {')
    for n in d['nav']:
        parts = []
        for k in ('Page', 'Id', 'Title'):
            if k in n:
                parts.append('%s = %s' % (k, q(n[k])))
        if 'Icon' in n:
            parts.append('Icon = 0x%X' % n['Icon'])
        if 'Children' in n:
            parts.append('Children = new[] { ' + ', '.join(q(c) for c in n['Children']) + ' }')
        if n.get('Categories'):
            parts.append('Categories = true')
        w('            new NavNode { %s },' % ', '.join(parts))
    w('        };')
    w('')
    w('        public static readonly Dictionary<string, string> Defaults = new Dictionary<string, string>(System.StringComparer.OrdinalIgnoreCase)')
    w('        {')
    for k, v in d['defaults'].items():
        w('            { %s, %s },' % (q(k), q(v)))
    w('        };')
    w('')
    w('        public static readonly string[] GAMEPAD_BUTTONS = { %s };' % ', '.join(q(x) for x in d['pad']))
    w('        public static readonly string[] SOURCES = { %s };' % ', '.join(q(x) for x in d['sources']))
    for name, key in (('STORE_LABELS', 'labels'), ('KEY_LABELS', 'keyLabels')):
        w('        public static readonly Dictionary<string, string> %s = new Dictionary<string, string>' % name)
        w('        {')
        for k, v in d[key].items():
            w('            { %s, %s },' % (q(k), q(v)))
        w('        };')
    w('    }')
    w('}')
    return '\n'.join(lines) + '\n'


def main():
    shell = shutil.which('pwsh') or shutil.which('powershell')
    if not shell:
        sys.exit('PowerShell (pwsh) is needed to read the schema of Options.ps1')
    env = dict(os.environ, RT_ROOT=ROOT)
    out = subprocess.run([shell, '-NoProfile', '-NonInteractive', '-Command', DUMP], env=env,
                         capture_output=True, text=True, encoding='utf-8')
    if out.returncode != 0:
        sys.exit('PowerShell failed:\n' + out.stderr)
    text = generate(json.loads(out.stdout.lstrip('﻿')))
    if '--check' in sys.argv:
        current = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if current != text:
            sys.exit('src/Options/SchemaData.cs is out of date: run python tools/gen_options_schema.py')
        print('SchemaData.cs is up to date')
        return
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('written ' + os.path.relpath(OUT, ROOT))


if __name__ == '__main__':
    main()
