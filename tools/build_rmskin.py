#!/usr/bin/env python3
"""Builds the Raintile .rmskin package from this repository.

    python tools/build_rmskin.py [--version 1.0.3] [--out dist]

The package holds the skin only (Raintile.ini, its mini-skins and @Resources,
with the Options program in @Resources/Bin when it has been built; not
README.md, docs, src, tools or the git files) and the HotKey plugin from
tools/plugins. Its version is Version= in Raintile.ini; with --version it must
match (used by the release workflow, with the tag's number).

An .rmskin is a zip followed by 16 bytes, which Rainmeter's installer checks:
the size of the zip (8 bytes, little endian), a flags byte and "RMSKIN\\0".
"""

import argparse
import io
import os
import re
import struct
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIN = 'Raintile'

# what goes in the package, relative to the repository
INCLUDE = ['Raintile.ini', 'Hotkey', 'Navigation', 'Typing', '@Resources']
# never packaged, wherever they are
EXCLUDE_NAMES = {'.gitignore', 'Thumbs.db', 'desktop.ini'}
# generated by the skin on the user's PC: only the empty folder is shipped
GENERATED = '@Resources/Generated/'

RMSKIN_INI = """[rmskin]
Name={skin}
Author=Derek3rd
Version={version}
LoadType=Skin
Load={skin}\\{skin}.ini
MinimumRainmeter=4.5.28.3936
MinimumWindows=10.0
"""


def skin_version():
    text = open(os.path.join(ROOT, 'Raintile.ini'), encoding='utf-8').read()
    m = re.search(r'(?m)^\s*Version\s*=\s*(\S+)\s*$', text)
    if not m:
        sys.exit('Version= not found in Raintile.ini')
    return m.group(1)


def skin_files():
    for item in INCLUDE:
        path = os.path.join(ROOT, item)
        if os.path.isfile(path):
            yield item
            continue
        for folder, dirs, files in os.walk(path):
            dirs.sort()
            for name in sorted(files):
                rel = os.path.relpath(os.path.join(folder, name), ROOT).replace(os.sep, '/')
                if name in EXCLUDE_NAMES:
                    continue
                if rel.startswith(GENERATED) and name != '.gitkeep':
                    continue
                yield rel


def build(version, out_dir):
    data = io.BytesIO()
    with zipfile.ZipFile(data, 'w', zipfile.ZIP_DEFLATED) as z:
        z.writestr('RMSKIN.ini', RMSKIN_INI.format(skin=SKIN, version=version))
        for rel in skin_files():
            z.write(os.path.join(ROOT, rel), 'Skins/%s/%s' % (SKIN, rel))
        for bits in ('32bit', '64bit'):
            dll = os.path.join(ROOT, 'tools', 'plugins', bits, 'HotKey.dll')
            if not os.path.isfile(dll):
                sys.exit('missing ' + dll)
            z.write(dll, 'Plugins/%s/HotKey.dll' % bits)
    if not os.path.isfile(os.path.join(ROOT, '@Resources', 'Bin', 'RaintileOptions.exe')):
        print('note: @Resources/Bin/RaintileOptions.exe not built: the package opens the PowerShell Options window')
    payload = data.getvalue()
    os.makedirs(out_dir, exist_ok=True)
    out = os.path.join(out_dir, '%s_%s.rmskin' % (SKIN, version))
    with open(out, 'wb') as f:
        f.write(payload)
        f.write(struct.pack('<qB7s', len(payload), 0, b'RMSKIN\x00'))
    return out


def check(path):
    """The checks Rainmeter's installer makes, plus a readable zip."""
    raw = open(path, 'rb').read()
    size, _flags, key = struct.unpack('<qB7s', raw[-16:])
    if key != b'RMSKIN\x00' or size != len(raw) - 16:
        sys.exit('bad package footer: ' + path)
    z = zipfile.ZipFile(io.BytesIO(raw[:size]))
    if z.testzip() is not None:
        sys.exit('damaged zip: ' + path)
    names = z.namelist()
    for required in ('RMSKIN.ini', 'Skins/%s/Raintile.ini' % SKIN, 'Plugins/64bit/HotKey.dll'):
        if required not in names:
            sys.exit('missing %s in %s' % (required, path))
    return len(raw), len(names)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--version', help='expected version (e.g. the tag without "v")')
    parser.add_argument('--out', default=os.path.join(ROOT, 'dist'))
    args = parser.parse_args()
    version = skin_version()
    # a tag with a version number (v1.0.3) must match; other tags are not checked
    if args.version and re.match(r'^[vV]?\d+(\.\d+)*$', args.version) and args.version.lstrip('vV') != version:
        sys.exit('Version= in Raintile.ini is %s, the release says %s: update Raintile.ini' % (version, args.version))
    out = build(version, args.out)
    size, count = check(out)
    print('%s: %d bytes, %d files' % (out, size, count))


if __name__ == '__main__':
    main()
